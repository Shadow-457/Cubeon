#!/usr/bin/env python3
"""Index the Minecraft PNGs and their animation metadata for the static editor."""

import base64
import json
from pathlib import Path
import struct


ROOT = Path(__file__).resolve().parents[1]


def build():
    entries = []
    local_sources = {}
    for path in sorted((ROOT / "textures").rglob("*.png")):
        content = path.read_bytes()
        if content[:8] != b"\x89PNG\r\n\x1a\n":
            raise ValueError(f"Invalid PNG: {path}")
        width, height = struct.unpack(">II", content[16:24])
        relative = path.relative_to(ROOT / "textures")
        entry = {
            "id": relative.with_suffix("").as_posix(),
            "n": relative.stem.replace("_", " ").title(),
            "folder": relative.parent.as_posix(),
            "src": path.relative_to(ROOT).as_posix(),
            "w": width,
            "h": height,
        }
        metadata = path.with_name(path.name + ".mcmeta")
        if metadata.exists():
            entry["mcmeta"] = json.loads(metadata.read_text())
            animation = entry["mcmeta"].get("animation")
            if animation is not None:
                entry["animation"] = animation
        entries.append(entry)
        local_sources[entry["id"]] = "data:image/png;base64," + base64.b64encode(content).decode("ascii")
    if not entries:
        raise ValueError("No PNGs found in textures/")
    header = "// Generated by tools/build_texture_catalog.py from textures/.\n"
    (ROOT / "textures-manifest.js").write_text(
        header + "window.MINECRAFT_TEXTURES=" + json.dumps(entries, separators=(",", ":")) + ";\n"
    )
    # Loaded only for file:// pages, where reading local PNG pixels is blocked by browsers.
    (ROOT / "textures-local.js").write_text(
        header + "window.MINECRAFT_TEXTURE_SOURCES=" + json.dumps(local_sources, separators=(",", ":")) + ";\n"
    )
    print(f"Indexed {len(entries):,} Minecraft textures in {len({e['folder'].split('/')[0] for e in entries})} categories.")


if __name__ == "__main__":
    build()
