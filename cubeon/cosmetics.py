def active(cfg: dict, slot: str) -> str | None:
    """The selected id for a slot, or None when the catalogue lost it."""
    key = "active_shoulder_item" if slot == "shoulder" else "active_back_item"
    return cfg.get(key)


def set_active(cfg: dict, slot: str, item_id: str | None) -> None:
    """Select (or clear) one slot, save, and mirror the choice into the game."""
    if slot not in SLOTS:
        raise ValueError(f"Unknown cosmetic slot: {slot}")
    if item_id is not None and get(item_id, None) is None:
        raise ValueError(f"Unknown cosmetic: {item_id}")
    if item_id is not None and get(item_id)["slot"] != slot:
        raise ValueError(f"{item_id} is not a {slot} item")
    cfg["active_shoulder_item" if slot == "shoulder" else "active_back_item"] = item_id
    sync_to_game(cfg)
    save_config(cfg)


def selection_payload(cfg: dict) -> dict:
    return {
        "version": 1,
        "shoulder": cfg.get("active_shoulder_item") or None,
        "back": cfg.get("active_back_item") or None,
    }


def game_config_path(game_dir: str | None = None) -> str:
    """``<gameDir>/config/cubeon-cosmetics.json`` for the given folder.

    No explicit folder means the instance currently being played, NOT the
    shared root: each instance has its own ``config/`` (Fabric passes it to
    the mod as the config dir), so writing to the shared root made the
    cosmetic silently vanish in game. Before the first launch
    ``active_game_dir()`` is the shared root, which is the old behaviour.
    """
    return os.path.join(game_dir or active_game_dir(), "config",
                        "cubeon-cosmetics.json")


def sync_to_game(cfg: dict, game_dir: str | None = None) -> str:
    """Write the active ids where the client mod looks for them.

    Atomic and change-aware: the mod polls the file's mtime, so rewriting an
    unchanged selection on every launch would make it reload its textures for
    nothing. Best-effort - a read-only game folder must never block a launch.
    """
    path = game_config_path(game_dir)
    payload = selection_payload(cfg)
    text = json.dumps(payload, indent=2) + "\n"
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        try:
            with open(path, encoding="utf-8") as fh:
                if fh.read() == text:
                    return path
        except OSError:
            pass
        handle, temporary = tempfile.mkstemp(dir=os.path.dirname(path),
                                            prefix=".cubeon-cosmetics-",
                                            suffix=".json")
        try:
            with os.fdopen(handle, "w", encoding="utf-8") as fh:
                fh.write(text)
            os.replace(temporary, path)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
    except OSError:
        pass
    return path
