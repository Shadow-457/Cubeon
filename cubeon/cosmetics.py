def render_thumbnail(item: dict, directory: str | None = None,
                     size: tuple[int, int] = (96, 96), yaw: float = 35.0,
                     pitch: float = 12.0) -> Image.Image:
    """A small isometric render of one item, for the Cosmetics cards.

    Painter's algorithm is enough here: every cosmetic is a handful of convex,
    non-intersecting boxes, so sorting whole faces by depth cannot produce the
    wrong overlap the way an interpenetrating model could.
    """
    import math

    faces = preview_faces(item, directory)
    if not faces:
        return Image.new("RGBA", size, (0, 0, 0, 0))
    vertices = [vertex for face in faces for vertex in face[0]]
    xs = [v[0] for v in vertices]
    ys = [v[1] for v in vertices]
    zs = [v[2] for v in vertices]
    centre = ((min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2,
              (min(zs) + max(zs)) / 2)
    span = max(max(xs) - min(xs), max(ys) - min(ys), max(zs) - min(zs), 1.0)
    scale = (min(size) - 12) / span
    yaw, pitch = math.radians(yaw), math.radians(pitch)

    def rotate(vertex, centred=True):
        x, y, z = (vertex[0] - (centre[0] if centred else 0),
                   vertex[1] - (centre[1] if centred else 0),
                   vertex[2] - (centre[2] if centred else 0))
        across = x * math.cos(yaw) + z * math.sin(yaw)
        depth = -x * math.sin(yaw) + z * math.cos(yaw)
        return (across,
                y * math.cos(pitch) - depth * math.sin(pitch),
                y * math.sin(pitch) + depth * math.cos(pitch))

    canvas = Image.new("RGBA", size, (0, 0, 0, 0))
    ordered = []
    for vertices3, normal, texture in faces:
        rotated_normal = rotate(normal, centred=False)
        if rotated_normal[2] <= 0.001:
            continue
        points = [rotate(v) for v in vertices3]
        screen = [(size[0] / 2 + p[0] * scale, size[1] / 2 - p[1] * scale)
                  for p in points]
        ordered.append((sum(p[2] for p in points) / 3, screen, points, normal,
                        texture))
    for _, screen, points, normal, texture in sorted(ordered, key=lambda f: f[0]):
        origin, horizontal, vertical = screen
        tex_w, tex_h = texture.size
        a = (horizontal[0] - origin[0]) / tex_w
        c = (horizontal[1] - origin[1]) / tex_w
        b = (vertical[0] - origin[0]) / tex_h
        d = (vertical[1] - origin[1]) / tex_h
        det = a * d - b * c
        if abs(det) < 1e-6:
            continue
        fourth = (horizontal[0] + vertical[0] - origin[0],
                  horizontal[1] + vertical[1] - origin[1])
        x0 = max(0, math.floor(min(origin[0], horizontal[0], vertical[0], fourth[0])))
        y0 = max(0, math.floor(min(origin[1], horizontal[1], vertical[1], fourth[1])))
        x1 = min(size[0], math.ceil(max(origin[0], horizontal[0], vertical[0], fourth[0])))
        y1 = min(size[1], math.ceil(max(origin[1], horizontal[1], vertical[1], fourth[1])))
        if x1 <= x0 or y1 <= y0:
            continue
        coeffs = (d / det, -b / det, (d * (x0 - origin[0]) - b * (y0 - origin[1])) / det,
                  -c / det, a / det, (-c * (x0 - origin[0]) + a * (y0 - origin[1])) / det)
        from PIL import ImageEnhance
        lighting = 0.72 + 0.28 * max(0, normal[1] * 0.5 + normal[2] * 0.8)
        tile = ImageEnhance.Brightness(texture).enhance(lighting).transform(
            (x1 - x0, y1 - y0), Image.Transform.AFFINE, coeffs,
            resample=Image.Resampling.NEAREST)
        canvas.alpha_composite(tile, (x0, y0))
    return canvas


