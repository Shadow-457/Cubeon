"""Original shoulder and back cosmetics, and the file the client mod reads.

The catalogue is generated by ``tools/gen_cosmetics.py`` and lives in two
places on purpose:

* ``assets/cosmetics/catalog.json`` + PNGs - what the launcher preview reads.
* the same files under ``mod/src/main/resources`` - what the Cubeon Client
  reads from its own jar at runtime.

One generator writes both, so a wing's geometry and its art cannot drift
between the 3D preview and the game.

WHAT IS ACTUALLY IN THE GAME
----------------------------
The client mod draws these as textured boxes attached to the player's body
(one render layer, mirrored for the second wing). The launcher only writes
which ids are active to ``<game>/config/cubeon-cosmetics.json``; the mod
validates them against its bundled catalogue and ignores anything it does not
know. That means an old jar plus a new launcher degrades to "no cosmetic"
instead of a missing texture or a crash.

The launcher never ships cosmetic art from a third party: every pixel here is
drawn by ``tools/gen_cosmetics.py``.
"""
from __future__ import annotations

import json
import os
import tempfile
import threading

from PIL import Image

from .config import save_config
from .paths import active_game_dir

SLOTS = ("shoulder", "back")

#: Absolute model-space attachment points (see gen_cosmetics.py).
ANCHORS = {
    "shoulder": (-7.0, 0.0, 0.0),
    "back": (0.0, 2.0, 2.2),
}

_REPO_ASSETS = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "assets", "cosmetics")

_lock = threading.Lock()
_catalog = None
_catalog_dir = None


def assets_dir(override: str | None = None) -> str:
    """Where ``catalog.json`` and the item PNGs live."""
    return override or _REPO_ASSETS


def _load(directory: str) -> dict:
    with open(os.path.join(directory, "catalog.json"), encoding="utf-8") as fh:
        return json.load(fh)


def catalog(directory: str | None = None) -> dict:
    """The parsed catalogue, cached per directory."""
    global _catalog, _catalog_dir
    directory = assets_dir(directory)
    with _lock:
        if _catalog is None or _catalog_dir != directory:
            _catalog = _load(directory)
            _catalog_dir = directory
        return _catalog


def invalidate_cache() -> None:
    global _catalog, _catalog_dir
    with _lock:
        _catalog = None
        _catalog_dir = None


def items(slot: str | None = None, directory: str | None = None) -> list[dict]:
    entries = catalog(directory).get("items", [])
    if slot is None:
        return list(entries)
    return [item for item in entries if item.get("slot") == slot]


def get(item_id: str | None, directory: str | None = None) -> dict | None:
    if not item_id:
        return None
    return next((item for item in items(None, directory)
                 if item.get("id") == item_id), None)


def texture_path(item: dict, directory: str | None = None) -> str:
    return os.path.join(assets_dir(directory), item["texture"])


def texture(item: dict, directory: str | None = None) -> Image.Image:
    with Image.open(texture_path(item, directory)) as source:
        return source.convert("RGBA")


# ---------------------------------------------------------------------------
# Atlas geometry - shared with tools/gen_cosmetics.py
# ---------------------------------------------------------------------------


def face_rects(box: dict) -> dict:
    """The six tile rectangles inside one box's atlas, in texture pixels.

    This is the same layout ``cubeon.appearance._box`` uses, kept in one place
    because the Java renderer recomputes it from the catalogue's ``uv``/``px``
    and a divergence would put a wing's leading edge on its trailing edge.
    """
    width, height, depth = box["size"]
    px = box["px"]
    u, v = box["uv"]
    return {
        "front": (u + depth * px, v + depth * px, width * px, height * px),
        "back": (u + (2 * depth + width) * px, v + depth * px,
                 width * px, height * px),
        "left": (u, v + depth * px, depth * px, height * px),
        "right": (u + (depth + width) * px, v + depth * px,
                  depth * px, height * px),
        "top": (u + depth * px, v, width * px, depth * px),
        "bottom": (u + (depth + width) * px, v, width * px, depth * px),
    }


def _tile(sheet: Image.Image, rect, flip: bool) -> Image.Image:
    x, y, width, height = rect
    tile = sheet.crop((x, y, x + width, y + height))
    if flip:
        tile = tile.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
    return tile


def preview_faces(item: dict, directory: str | None = None) -> list[tuple]:
    """``(vertices, normal, texture)`` triples in the preview's space.

    Preview space is the one ``cubeon.appearance.CharacterModel`` already
    renders in: +y is up with the feet at 0 and the head top at 32, and +z is
    the player's front. Minecraft model space is y-down with -z as the front,
    so the conversion is ``y' = 24 - y`` and ``z' = -z``.
    """
    sheet = texture(item, directory)
    anchor_x = ANCHORS[item["slot"]][0]
    result = []
    for box in item.get("boxes", []):
        rects = face_rects(box)
        copies = (False, True) if box.get("mirror") else (False,)
        for mirrored in copies:
            x0, y0, z0 = box["origin"]
            width, height, depth = box["size"]
            x1, y1, z1 = x0 + width, y0 + height, z0 + depth
            if mirrored:
                x0, x1 = 2 * anchor_x - x1, 2 * anchor_x - x0
            # Minecraft -> preview.
            bottom, top = 24 - y1, 24 - y0
            back, front = -z1, -z0
            faces = {
                "front": ([(x0, top, front), (x1, top, front), (x0, bottom, front)],
                          (0, 0, 1)),
                "back": ([(x1, top, back), (x0, top, back), (x1, bottom, back)],
                         (0, 0, -1)),
                "left": ([(x1, top, front), (x1, top, back), (x1, bottom, front)],
                         (1, 0, 0)),
                "right": ([(x0, top, back), (x0, top, front), (x0, bottom, back)],
                          (-1, 0, 0)),
                "top": ([(x0, top, back), (x1, top, back), (x0, top, front)],
                        (0, 1, 0)),
                "bottom": ([(x0, bottom, front), (x1, bottom, front),
                            (x0, bottom, back)], (0, -1, 0)),
            }
            for name, (vertices, normal) in faces.items():
                source = name
                if mirrored and name in ("left", "right"):
                    source = "right" if name == "left" else "left"
                tile = _tile(sheet, rects[source], mirrored)
                if tile.getbbox():
                    result.append((vertices, normal, tile))
    return result


