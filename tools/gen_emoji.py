#!/usr/bin/env python3
"""Generate the offline shortcode catalog from pinned Unicode emoji-test data.

Run with --source for a saved copy; otherwise fetch the versioned public file.
The launcher imports the generated table and never downloads emoji metadata.
"""
import argparse
import hashlib
from pathlib import Path
import re
import unicodedata
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
VERSION = '18.0'
SOURCE = f'https://unicode.org/Public/{VERSION}.0/emoji/emoji-test.txt'
ENTRY = re.compile(r'^([0-9A-F ]+)\s*;\s*(fully-qualified|component)\s*#\s*\S+\s+E[0-9.]+\s+(.+)$')


def catalog(body):
    text = body.decode('utf-8')
    if f'# Version: {VERSION}\n' not in text:
        raise ValueError('Unexpected Unicode emoji version')
    table = {}
    sequences = set()
    for line in text.splitlines():
        match = ENTRY.match(line)
        if not match:
            continue
        points = [int(value, 16) for value in match[1].split()]
        emoji = ''.join(map(chr, points))
        name = match[3].replace('#', ' number sign ').replace('*', ' asterisk ')
        name = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode().lower()
        code = re.sub(r'[^a-z0-9]+', '_', name).strip('_')
        if not code or (code in table and table[code] != emoji):
            raise ValueError(f'Duplicate/empty shortcode: {match[3]}')
        table[code] = emoji
        sequences.add(emoji)
        if len(points) == 2 and all(0x1F1E6 <= point <= 0x1F1FF for point in points):
            country = ''.join(chr(point - 0x1F1E6 + ord('a')) for point in points)
            table['flag_' + country] = emoji
    expected = sum(int(count) for count in re.findall(
        r'^# (?:fully-qualified|component) : (\d+)$', text, re.MULTILINE))
    if len(sequences) < 3900 or len(sequences) != expected:
        raise ValueError('Incomplete Unicode emoji data')
    return table, len(sequences)


def generate(body):
    table, count = catalog(body)
    lines = [
        '"""Generated by tools/gen_emoji.py; Unicode data uses assets/emoji/UNICODE-LICENSE.txt."""',
        f'UNICODE_VERSION = {VERSION!r}', f'SOURCE_URL = {SOURCE!r}',
        f'SOURCE_SHA256 = {hashlib.sha256(body).hexdigest()!r}', f'EMOJI_COUNT = {count}',
        'UNICODE_SHORTCODES = {',
    ]
    lines.extend(f'    {code!r}: {value!r},' for code, value in sorted(table.items()))
    return '\n'.join(lines + ['}', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.source:
        body = args.source.read_bytes()
    else:
        with urlopen(SOURCE, timeout=25) as response:
            body = response.read(1_000_001)
        if len(body) > 1_000_000:
            raise ValueError('Unicode source is too large')
    output = ROOT / 'cubeon' / '_emoji_data.py'
    generated = generate(body)
    if args.check:
        assert output.read_text(encoding='utf-8') == generated, 'Regenerate the emoji catalog'
    else:
        output.write_text(generated, encoding='utf-8')
    print(f'{catalog(body)[1]} Unicode {VERSION} emoji sequences; {output}')
